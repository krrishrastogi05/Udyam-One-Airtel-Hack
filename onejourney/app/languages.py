FIELDS = ("business_type", "employees", "sites", "city_tier", "budget", "needs")


def normalize_digits(text):
    return "".join(
        str(unicodedata.decimal(ch)) if ch.isdecimal() else ch for ch in text
    )


def missing_field(profile):
    return next(
        (i for i, k in enumerate(FIELDS) if profile.get(k) in (None, "", [])), None
    )
